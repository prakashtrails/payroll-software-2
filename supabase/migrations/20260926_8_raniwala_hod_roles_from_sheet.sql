SELECT * FROM (VALUES
  ('RAMESH YADAV', '707'), ('MANOJ SHARMA', '740'), ('IMRAN KHAN', '356'), ('GANESH SHARMA', '2'),
  ('MEHUL VITHLANI', '82'), ('PRATIBHA VASHISHTA', '339'), ('BHANWAR SINGH', '194'), ('PUSHPENDRA SINGH', '64')
