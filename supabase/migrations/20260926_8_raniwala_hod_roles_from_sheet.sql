-- Name-to-name aliases (profile renamed / duplicate inactive record).
CREATE TEMP TABLE _name_alias ON COMMIT DROP AS
SELECT * FROM (VALUES ('PALASH BARMAN', 'POLASH BARMAN')) AS a(name, db_name);

CREATE TEMP TABLE _p ON COMMIT DROP AS
SELECT p.id, p.employee_id, p.role, p.status,
       upper(regexp_replace(trim(concat_ws(' ', p.first_name, p.middle_name, p.last_name)), '\s+', ' ', 'g')) AS nm
FROM profiles p JOIN tenants t ON t.id = p.tenant_id
WHERE t.company_name ILIKE '%Raniwala%';

-- Sheet row -> profile: code (name must agree only when the sheet reuses
-- that code for several people), else unique exact name.
CREATE TEMP TABLE _emp ON COMMIT DROP AS
SELECT s.xl_row, s.name, s.mgr, s.hod,
       COALESCE(
         (SELECT p.id FROM _p p WHERE s.code <> '' AND p.employee_id = s.code
            AND (p.nm = s.name OR p.nm LIKE s.name || ' %'
                 OR (SELECT count(DISTINCT x.name) FROM _sheet x WHERE x.code = s.code) = 1) LIMIT 1),
         (SELECT min(p.id::text)::uuid FROM _p p WHERE p.nm = s.name HAVING count(*) = 1)
       ) AS pid
FROM _sheet s;

-- Leader name -> profile: alias code, else that person's own sheet row,
-- else a unique exact name.
CREATE TEMP TABLE _leader ON COMMIT DROP AS
SELECT l.name,
       COALESCE(
         (SELECT p.id FROM _alias a JOIN _p p ON p.employee_id = a.code WHERE a.name = l.name LIMIT 1),
         (SELECT p.id FROM _name_alias a JOIN _p p ON p.nm = a.db_name AND p.status = 'Active' WHERE a.name = l.name LIMIT 1),
         (SELECT e.pid FROM _emp e WHERE e.name = l.name AND e.pid IS NOT NULL LIMIT 1),
         (SELECT min(p.id::text)::uuid FROM _p p WHERE p.nm = l.name HAVING count(*) = 1)
       ) AS pid
FROM (SELECT mgr AS name FROM _sheet UNION SELECT hod FROM _sheet) l;

-- Roles: HODs first, then managers (never demote HR, never touch Inactive).
UPDATE profiles p SET role = 'hod'
FROM _leader l
WHERE p.id = l.pid AND l.name IN (SELECT hod FROM _sheet)
  AND p.role IN ('employee', 'manager') AND p.status = 'Active';

UPDATE profiles p SET role = 'manager'
FROM _leader l
WHERE p.id = l.pid AND l.name IN (SELECT mgr FROM _sheet)
  AND p.role = 'employee' AND p.status = 'Active';

-- Explicit HOD per employee (manager_id is left as 20260926_7 set it).
UPDATE profiles p
SET hod_id = CASE WHEN lh.pid = e.pid THEN NULL
                  WHEN (SELECT role FROM profiles WHERE id = lh.pid) = 'hod' THEN lh.pid END
FROM _emp e
LEFT JOIN _leader lh ON lh.name = e.hod
WHERE p.id = e.pid;

