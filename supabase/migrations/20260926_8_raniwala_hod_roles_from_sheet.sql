-- ── 1. hod_id ─────────────────────────────────────────────────────────────
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS hod_id uuid REFERENCES profiles(id) ON DELETE SET NULL;

CREATE OR REPLACE VIEW profile_directory AS
  SELECT id, tenant_id, first_name, middle_name, last_name, employee_id, role, status,
         department, designation, division, manager_id, outlet_id, outlet_location, hod_id
  FROM profiles p
  WHERE tenant_id = (SELECT my_tenant_id()) OR (SELECT my_role()) = 'superadmin';


-- ── 2. Functions ──────────────────────────────────────────────────────────
-- HOD: explicit hod_id when it points at an active HOD, else the first HOD
-- up the manager_id chain. Manager: first active role='manager' ancestor.
CREATE OR REPLACE FUNCTION resolve_leave_approvers(p_profile_id uuid, OUT o_manager uuid, OUT o_hod uuid)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_cur  uuid;
  v_next uuid;
  v_role text;
  v_status text;
  v_chain_hod uuid;
  i int := 0;
BEGIN
  SELECT manager_id INTO v_cur FROM profiles WHERE id = p_profile_id;
  WHILE v_cur IS NOT NULL AND v_cur <> p_profile_id AND i < 8 LOOP
    SELECT role, status, manager_id INTO v_role, v_status, v_next FROM profiles WHERE id = v_cur;
    IF COALESCE(v_status, 'Active') = 'Active' THEN
      IF v_role = 'manager' AND o_manager IS NULL THEN
        o_manager := v_cur;
      ELSIF v_role = 'hod' THEN
        v_chain_hod := v_cur;
        EXIT;
      ELSIF v_role IN ('management', 'admin', 'superadmin') THEN
        EXIT;
      END IF;
    END IF;
    v_cur := v_next;
    i := i + 1;
  END LOOP;

  SELECT h.id INTO o_hod
  FROM profiles e JOIN profiles h ON h.id = e.hod_id
  WHERE e.id = p_profile_id AND h.role = 'hod' AND h.status = 'Active' AND h.id <> p_profile_id;
  o_hod := COALESCE(o_hod, v_chain_hod);

  -- A manager who is also the employee's HOD only approves once, as HOD.
  IF o_manager = o_hod THEN
    o_manager := NULL;
  END IF;
END;
$$;

-- Team = everyone below the caller in the manager_id tree, plus (for an
-- HOD) everyone whose hod_id is the caller and everyone below them.
CREATE OR REPLACE FUNCTION my_team_ids()
RETURNS uuid[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  WITH RECURSIVE tree(id, depth) AS (
    SELECT p.id, 1 FROM profiles p
    WHERE (p.manager_id = auth.uid() OR p.hod_id = auth.uid()) AND p.id <> auth.uid()
    UNION
    SELECT p.id, t.depth + 1 FROM profiles p JOIN tree t ON p.manager_id = t.id
    WHERE t.depth < 6 AND p.id <> auth.uid()
  )
  SELECT COALESCE(array_agg(DISTINCT id), '{}'::uuid[]) FROM tree;
$$;

CREATE OR REPLACE FUNCTION is_in_team_of(p_member uuid, p_leader uuid)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_cur uuid;
  i int := 0;
BEGIN
  v_cur := p_member;
  WHILE v_cur IS NOT NULL AND i < 8 LOOP
    IF EXISTS (SELECT 1 FROM profiles WHERE id = v_cur AND (manager_id = p_leader OR hod_id = p_leader)) THEN
      RETURN true;
    END IF;
    SELECT manager_id INTO v_cur FROM profiles WHERE id = v_cur;
    i := i + 1;
  END LOOP;
  RETURN false;
END;
$$;


